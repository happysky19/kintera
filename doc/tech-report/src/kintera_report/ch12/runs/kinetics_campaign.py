"""Producer for derivation-checks/ch12/saved-preparation/kinetics{64,32}.jsonl.

    KINTERA_REPO=<kintera checkout> CH12_SAVED=<saved-preparation> \
        python -P src/kintera_report/ch12/runs/kinetics_campaign.py --out <dir>

This is the paired CPU/CUDA campaign behind `^ch12-dispatch-agree`. The chapter cites the saved
records; `check_ch12_spec_complement.py conditioning` reads them back and reconstructs the inputs
CPU-only. What was missing was the producer that writes them, so the saved numbers could not be
regenerated by anyone but their author.

The inputs are not re-invented here. They are built exactly as `conditioning()` builds them --
same decks and deck order, seed 20261020, 64 cells per deck and precision, dt 10 s, 80 to 120 K for
the two test decks and 180 to 220 K for Jupiter, 1e3.5 to 1e4.5 Pa with the three cells either side
of 1e4, random concentrations, and the Kessler saturation column -- so a record this writes is
comparable with the record already saved. The difference is that this runs each quantity on both
devices and reports the agreement, which is what the chapter claims.

Quantities compared per deck, as the chapter names them: `Kinetics.forward_with_rate_constants`
(rate and dkdC), `Kinetics.jacobian`, and `evolve_implicit` (step). Each record carries the finite
masks, the largest difference, the largest difference over the largest CPU value, and how many
entries fall outside atol 1e-12 / rtol 1e-10 -- the schema already in the saved files.

`--check` compares what this run produces against the saved records instead of writing, and exits
non-zero on a difference. It never rewrites a saved file unless `--out` is given explicitly.
"""
import argparse
import importlib.util
import json
import os
import pathlib
import sys

SEED = 20261020
CELLS = 64
DT = 10.0
ATOL, RTOL = 1e-12, 1e-10
DECKS = ("test_evaporation_kessler", "test_coagulation_pressure_switch", "jupiter")


def _env(name):
    v = os.environ.get(name)
    if not v:
        sys.exit(f"kinetics_campaign.py: set {name}")
    return pathlib.Path(v)


def build_inputs(torch, kt, name, dtype, root, saved):
    """the inputs of check_ch12_spec_complement.conditioning(), unchanged"""
    if name == "jupiter":
        path = root / "tests" / "jupiter.yaml"
    else:
        spec = importlib.util.spec_from_file_location(name, root / "tests" / f"{name}.py")
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        path = saved / (name + ".yaml")
    op = kt.KineticsOptions.from_yaml(str(path))
    n = len(op.species())
    gen = torch.Generator().manual_seed(SEED)
    if name != "jupiter":
        T = (80 + 40 * torch.rand(CELLS, generator=gen)).to(dtype)
    else:
        T = (180 + 40 * torch.rand(CELLS, generator=gen)).to(dtype)
    P = (10 ** (3.5 + torch.rand(CELLS, generator=gen))).to(dtype)
    p0 = torch.tensor(1e4, dtype=dtype)
    P[:3] = torch.stack([torch.nextafter(p0, torch.tensor(0., dtype=dtype)), p0,
                         torch.nextafter(p0, torch.tensor(float("inf"), dtype=dtype))])
    C = (1e-3 * torch.rand(CELLS, n, generator=gen)).to(dtype)
    if "kessler" in name:
        sat = torch.tensor([m.svp(float(t)) / (m.R * float(t)) for t in T], dtype=dtype)
        C[:, op.species().index("CH4")] = sat * torch.linspace(.5, 1.5, CELLS, dtype=dtype)
    return op, T, P, C, n


def quantities(torch, kt, op, T, P, C, dtype, device):
    kin = kt.Kinetics(op)
    kin.to(dtype)
    # .to() is in-place here and returns None, so it is called for its effect, not rebound;
    # and it resolves a str to a dtype, so the device has to arrive as a torch.device.
    dev = torch.device(device)
    kin.to(dev)
    t, p, c = T.to(dev), P.to(dev), C.to(dev)
    if not hasattr(kin, "forward_with_rate_constants"):
        raise RuntimeError("this kintera has no Kinetics.forward_with_rate_constants; "
                           "the chapter pins kintera@0d9f67f9 (v2.6.5), where it exists")
    r, dc, dt_, k = kin.forward_with_rate_constants(t, p, c)
    J = kin.jacobian(t, c, torch.ones_like(t), r, dc, dt_)
    step = kt.evolve_implicit(r, kin.buffer("stoich").to(device), J, DT)
    return {"rate": r, "dkdC": dc, "jacobian": J, "step": step}


def agreement(torch, label, dtype, a, b):
    """one saved record: the CPU/CUDA agreement of one quantity"""
    a64, b64 = a.double().cpu(), b.double().cpu()
    fa, fb = a64.isfinite(), b64.isfinite()
    d = (a64 - b64).abs()
    finite_both = fa & fb
    denom = a64.abs().max().clamp_min(torch.finfo(torch.float64).tiny)
    tol = ATOL + RTOL * b64.abs()
    return {"label": label, "dtype": str(dtype), "count": int(a64.numel()),
            "finite_cpu": int(fa.sum()), "finite_cuda": int(fb.sum()),
            "finite_mask_mismatch": int((fa != fb).sum()),
            "nan_mask_mismatch": int((a64.isnan() != b64.isnan()).sum()),
            "inf_sign_mismatch": int(((a64.isinf() | b64.isinf()) & (a64.sign() != b64.sign())).sum()),
            "max_abs": float(d[finite_both].max()) if int(finite_both.sum()) else 0.0,
            "max_abs_over_cpu_max": float(d[finite_both].max() / denom) if int(finite_both.sum()) else 0.0,
            "outside_tolerance": int((d > tol)[finite_both].sum()),
            "atol": ATOL, "rtol": RTOL, "seed": SEED, "cells": CELLS, "dt": DT}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", help="directory to write kinetics{64,32}.jsonl into")
    ap.add_argument("--check", action="store_true", help="compare with the saved records, write nothing")
    args = ap.parse_args()
    if not args.out and not args.check:
        sys.exit("kinetics_campaign.py: pass --out <dir> to write, or --check to compare")

    try:
        import torch
        import kintera as kt
    except ImportError as e:
        sys.exit(f"kinetics_campaign.py: {e}. Build and install kintera first.")
    if not torch.cuda.is_available():
        print("kinetics_campaign.py: SKIPPED, no CUDA device visible; this campaign is a CPU/CUDA pair",
              file=sys.stderr)
        return 3

    root, saved = _env("KINTERA_REPO"), _env("CH12_SAVED")
    print(f"kintera {kt.__version__}; seed {SEED}, {CELLS} cells per deck and precision, dt {DT:g} s")
    bad = 0
    for dtype, fname in ((torch.float64, "kinetics64.jsonl"), (torch.float32, "kinetics32.jsonl")):
        records = []
        for name in DECKS:
            op, T, P, C, _ = build_inputs(torch, kt, name, dtype, root, saved)
            cpu = quantities(torch, kt, op, T, P, C, dtype, "cpu")
            gpu = quantities(torch, kt, op, T, P, C, dtype, "cuda")
            for q in ("rate", "dkdC", "jacobian", "step"):
                records.append(agreement(torch, f"{name}/{q}", dtype, cpu[q], gpu[q]))
        if args.check:
            old = {json.loads(l)["label"] + "|" + json.loads(l)["dtype"]: json.loads(l)
                   for l in (saved / fname).read_text().splitlines()}
            for r in records:
                key = r["label"] + "|" + r["dtype"]
                if key not in old:
                    print(f"  NEW   {key}: not in {fname}")
                    bad += 1
                    continue
                for field in ("outside_tolerance", "finite_mask_mismatch"):
                    if old[key][field] != r[field]:
                        print(f"  DIFF  {key}.{field}: saved {old[key][field]} -> now {r[field]}")
                        bad += 1
            print(f"  {fname}: {len(records)} record(s) compared")
        else:
            out = pathlib.Path(args.out)
            out.mkdir(parents=True, exist_ok=True)
            (out / fname).write_text("".join(json.dumps(r) + "\n" for r in records))
            print(f"  wrote {out / fname}: {len(records)} record(s)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
